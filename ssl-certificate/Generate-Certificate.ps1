# ==================================================================================================
# DeskGuard for Microsoft Outlook - Self-Signed Code Signing Certificate Generator
# Generates a dedicated self-signed Authenticode Code Signing certificate (EKU: Code Signing)
# ==================================================================================================
param(
    [string]$CertSubject = "CN=DeskGuard for Microsoft Outlook, O=DeskGuard Security, C=US",
    [string]$OutputDir = $PSScriptRoot,
    [string]$Password = $env:DESKGUARD_CERT_PASS
)

if ([string]::IsNullOrWhiteSpace($Password)) {
    $Password = "DeskGuard_LocalDev_SecuredKey_2026!"
}

$pfxPath = Join-Path $OutputDir "DeskGuard_CodeSigning.pfx"
$cerPath = Join-Path $OutputDir "DeskGuard_CodeSigning.cer"
$rsaPubKeyPath = Join-Path $OutputDir "DeskGuard_ManifestPublicKey.pem"

Write-Host "==> Generating Self-Signed Code Signing Certificate for DeskGuard..." -ForegroundColor Cyan

# Check if cert already exists
if (Test-Path $pfxPath) {
    Write-Host "Found existing certificate at: $pfxPath" -ForegroundColor Green
    exit 0
}

# Generate Code Signing Certificate (EKU 1.3.6.1.5.5.7.3.3)
$cert = New-SelfSignedCertificate `
    -Subject $CertSubject `
    -Type CodeSigningCert `
    -KeyUsage DigitalSignature `
    -KeyLength 3072 `
    -KeyAlgorithm RSA `
    -HashAlgorithm SHA256 `
    -CertStoreLocation "Cert:\CurrentUser\My" `
    -NotAfter (Get-Date).AddYears(5)

Write-Host "Created Certificate Thumbprint: $($cert.Thumbprint)" -ForegroundColor Yellow

# Export PFX with Private Key
$securePass = ConvertTo-SecureString -String $Password -Force -AsPlainText
Export-PfxCertificate -Cert $cert -FilePath $pfxPath -Password $securePass | Out-Null
Write-Host "Exported PFX: $pfxPath" -ForegroundColor Green

# Export CER (Public Key Only)
Export-Certificate -Cert $cert -FilePath $cerPath | Out-Null
Write-Host "Exported CER: $cerPath" -ForegroundColor Green

# Export RSA Public Key in PEM format for manifest signature validation
$rsa = [System.Security.Cryptography.X509Certificates.RSACertificateExtensions]::GetRSAPublicKey($cert)
$pubKeyBytes = $rsa.ExportSubjectPublicKeyInfo()
$pubKeyBase64 = [Convert]::ToBase64String($pubKeyBytes, [Base64FormattingOptions]::InsertLineBreaks)
$pemContent = "-----BEGIN PUBLIC KEY-----`n$pubKeyBase64`n-----END PUBLIC KEY-----"
Set-Content -Path $rsaPubKeyPath -Value $pemContent -Encoding UTF8
Write-Host "Exported RSA Public Key PEM: $rsaPubKeyPath" -ForegroundColor Green

# Export C# byte array constant file for embedding into DeskGuard.App and DeskGuard.Build
$csConstPath = Join-Path $OutputDir "SigningConstants.cs"
$pubKeyHex = ($pubKeyBytes | ForEach-Object { "0x{0:X2}" -f $_ }) -join ", "
$csContent = @"
// <auto-generated> DeskGuard Code Signing & Manifest Verification Constants </auto-generated>
namespace DeskGuard.Core.Security;

public static class SigningConstants
{
    public const string DefaultCertificatePassword = "$Password";
    public static readonly byte[] ManifestPublicKeyBytes = [ $pubKeyHex ];
}
"@
Set-Content -Path $csConstPath -Value $csContent -Encoding UTF8
Write-Host "Exported C# SigningConstants: $csConstPath" -ForegroundColor Green

Write-Host "Self-Signed Code Signing Certificate generation completed successfully!" -ForegroundColor Green
